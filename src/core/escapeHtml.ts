/**
 * Escapes HTML special characters to prevent markup injection or broken attributes
 * when interpolating translated strings or page text into HTML template strings.
 */
export function escapeHtml(str: string): string {
  return str
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;")
}
